# ─── 6. 最简单的类 ───
# class = 定义类的关键字
# 类 = "模板"，用来创建多个相似的"对象"

class Student:
    """
    学生类。

    用 class 定义一个"学生"的模板。
    以后每个学生都有 name 和 score 两个属性。
    """
    pass  # pass = 占位符，"这里先空着"

# 用类创建对象
s1 = Student()  # s1 是一个 Student 实例
s1.name = "小明"  # 给实例添加属性
s1.score = 95
print(f"{s1.name} 的成绩是 {s1.score}")


# ─── 7. 带构造方法的类 ───
# __init__ 是"构造方法"，创建对象时自动调用
# 用来给新对象设置初始值

class Dog:
    """
    狗类。

    __init__ 方法：
    - 创建实例时自动执行
    - self 代表"这个实例本身"
    - name 和 age 是创建时必须传入的参数
    """

    def __init__(self, name, age):
        """
        构造方法：创建 Dog 实例时自动调用。

        Parameters
        ----------
        name : str
            狗的名字。
        age : int
            狗的年龄。
        """
        self.name = name  # self.name 是实例的属性
        self.age = age    # 右边的 name 是传入的参数
        print(f"一只名叫 {name} 的狗出生了！")

    def bark(self):
        """
        实例方法：让狗叫。

        注意：每个实例方法第一个参数必须是 self，
        但调用时不用传 self，Python 自动处理。
        """
        print(f"{self.name} 说：汪汪！")

    def __str__(self):
        """
        特殊方法：print(对象) 时自动调用。
        返回人类能看懂的描述。
        """
        return f"Dog(name={self.name}, age={self.age})"

# 创建 Dog 实例
dog1 = Dog("旺财", 3)  # __init__ 自动执行
dog2 = Dog("小白", 1)

# 调用实例方法
dog1.bark()  # 输出：旺财 说：汪汪！
dog2.bark()  # 输出：小白 说：汪汪！

# print 对象时调用 __str__
print(dog1)  # 输出：Dog(name=旺财, age=3)


# ─── 8. 类属性 vs 实例属性 ───
# 类属性：所有实例共享（写在类里面，方法外面）
# 实例属性：每个实例独有（写在 __init__ 里）

class Cat:
    # 类属性：所有猫共享
    species = "家猫"
    total_count = 0  # 统计一共创建了多少只猫

    def __init__(self, name, color):
        # 实例属性：每只猫自己的
        self.name = name
        self.color = color
        Cat.total_count += 1  # 每创建一只，总数 +1

# 类属性通过"类名.属性"或"实例.属性"都能访问
print(f"猫的物种是：{Cat.species}")

cat1 = Cat("咪咪", "橘色")
cat2 = Cat("小黑", "黑色")

print(f"{cat1.name} 是 {cat1.color}的{cat1.species}")
print(f"一共创建了 {Cat.total_count} 只猫")  # 输出：一共创建了 2 只猫


