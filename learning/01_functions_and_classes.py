# ─── 5. 类型提示（写给人和IDE看的） ───
# Python 是动态类型，但可以加提示让代码更清晰
# 注意：这只是提示，不会强制检查，写错了也能运行

def calculate_bmi(weight: float, height: float) -> str:
    """
    计算 BMI 指数。

    :param weight: 体重（kg）
    :param height: 身高（m）
    :return: BMI 结果描述
    """
    bmi = weight / (height ** 2)  # ** 是乘方，height ** 2 = height²
    if bmi < 18.5:
        return "偏瘦"
    elif bmi < 24:
        return "正常"
    else:
        return "偏重"

result = calculate_bmi(70, 1.75)
print(f"BMI 结果：{result}")  # 输出：BMI 结果：正常


