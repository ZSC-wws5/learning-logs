# ─── 1. 最简单的函数 ───
# def = define（定义），意思是我在创造一个函数
# 函数是一段可以反复使用的代码

def say_hello():
    """
    最简单的函数：没有参数，没有返回值。
    只管打印一句话。
    """
    print("你好！")

# 调用函数 = 让它执行
say_hello()  # 控制台会输出：你好！
say_hello()  # 可以反复调用


# ─── 2. 带参数的函数 ───
# 参数 = 你给函数的"输入"，函数根据输入做不同的事

def greet(name):
    """
    接收一个参数 name，打印个性化的问候语。

    Parameters
    ----------
    name : str
        要问候的人名。
    """
    print(f"你好，{name}！欢迎学习 Python！")

greet("小明")  # 输出：你好，小明！欢迎学习 Python！
greet("小红")  # 输出：你好，小红！欢迎学习 Python！


# ─── 3. 带返回值的函数 ───
# return = 把结果"交回来"，这样调用者可以拿到结果继续用

def add(a, b):
    """
    接收两个数字，返回它们的和。

    Parameters
    ----------
    a, b : int 或 float
        要相加的两个数。

    Returns
    -------
    a + b 的计算结果。
    """
    result = a + b
    return result  # return 把值返回给调用者

# 调用时，返回值可以被变量接住
sum_result = add(3, 5)
print(f"3 + 5 = {sum_result}")  # 输出：3 + 5 = 8

# return 还有一个作用：函数执行到 return 就立刻结束
def check_age(age):
    if age < 0:
        return "年龄不能是负数！"  # 这里 return 了，下面代码不执行
    return f"你的年龄是 {age}"


# ─── 4. 默认参数 ───
# 有些参数"大部分时候用同一个值"，可以给个默认值

def greet_with_title(name, title="同学"):
    """
    带默认参数的函数。
    如果不传 title，就默认用"同学"。
    """
    print(f"{title} {name}，你好！")

greet_with_title("小明")           # 输出：同学 小明，你好！
greet_with_title("王老师", "老师")  # 输出：老师 王老师，你好！

